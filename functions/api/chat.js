import { SYSTEM_PROMPT } from './systemPrompt.js';

// ─── constants ───────────────────────────────────────────────────────────────

const GROQ_URL        = 'https://api.groq.com/openai/v1/chat/completions';
const MODEL           = 'qwen/qwen3.6-27b';
const MAX_TOOL_ROUNDS = 2;

const MAX_RESULTS       = 5;
const MAX_TITLE_LEN     = 120;
const MAX_URL_LEN       = 300;
const MAX_SNIPPET_LEN   = 600;
const MAX_PAGE_TEXT_LEN = 3000;
const SNIPPET_FETCH_MIN = 350;

const TIMEOUT_SEARXNG_MS = 6_000;
const TIMEOUT_PAGE_MS    = 4_000;
const TIMEOUT_GROQ_MS    = 55_000;

// ─── zero-cost freshness gate ────────────────────────────────────────────────
//
// Pure JS — zero AI calls. Returns true when the query clearly requests
// volatile/current information. Used ONLY to decide tool_choice: "required"
// vs "auto". The actual search query is always generated by Qwen.
//
// Deliberately narrow: named entities alone do NOT trigger it.
// "What is Apple?" → false. "Apple ki current market cap?" → true.
//

